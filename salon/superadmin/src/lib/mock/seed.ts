export function buildMockBookings(): Booking[] {
  const bookings: Booking[] = [];
  let idx = 0;
  // Spread bookings across the past 5 days, today, and the next 7 days.
  for (let offset = -5; offset <= 7; offset++) {
    const count = offset === 0 ? 6 : 1 + ((offset + idx) % 3);
    for (let i = 0; i < count; i++) {
      const name = names[idx % names.length];
      const barber = mockBarbersSeed[idx % mockBarbersSeed.length];
      const serviceName = services[idx % services.length];
      const serviceMeta = mockServicesFullSeed.find((s) => s.name === serviceName);
      const status = offset < 0 ? (idx % 4 === 0 ? "no_show" : "completed") : statuses[idx % statuses.length];
      bookings.push({
        _id: `mock-${offset}-${i}`,
        bookingId: `BK${(1000 + idx).toString()}`,
        customerName: name,
        customerPhone: `+1 (555) 234-10${(idx % names.length) + 1}`.slice(0, 18),
        customerEmail: `${name.split(" ")[0].toLowerCase()}.${name.split(" ")[1].toLowerCase()}@example.com`,
        service: serviceName,
        serviceId: serviceMeta?._id ?? serviceName,
        barber: barber.name,
        barberId: barber._id,
        branchId: barber.branchId,
        date: isoDaysFromToday(offset),
        time: times[idx % times.length],
        total: serviceMeta?.price ?? 20 + ((idx * 7) % 60),
        status,
        notes: idx % 5 === 0 ? "Prefers window seat area" : undefined,
      });
      idx++;
    }
  }
  return bookings;
}

